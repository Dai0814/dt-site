const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const inputPath = path.join(root, "assets", "china-regions.sql");
const outputPath = path.join(root, "assets", "china-city-index.js");

const sql = fs.readFileSync(inputPath, "utf8");
const rows = [];
const rowPattern = /\('([^']*)','([^']*)','([^']*)','([^']*)','([^']*)','[^']*',(?:NULL|'[^']*')\)/g;
let match;

while ((match = rowPattern.exec(sql))) {
  const [, id, name, parentId, lon, lat] = match;
  const longitude = Number(lon);
  const latitude = Number(lat);
  if (!id || !name || !Number.isFinite(longitude) || !Number.isFinite(latitude)) continue;
  rows.push({ id, name, parentId, lon: longitude, lat: latitude });
}

const byId = new Map(rows.map((row) => [row.id, row]));
const genericNames = new Set(["市辖区", "县", "省直辖县级行政区划", "自治区直辖县级行政区划"]);
const suffixPattern = /(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|自治州|自治县|自治旗|地区|盟|省|市|区|县|旗)$/g;

function getPath(row) {
  const pathRows = [];
  const seen = new Set();
  let current = row;

  while (current && !seen.has(current.id)) {
    seen.add(current.id);
    pathRows.unshift(current);
    current = current.parentId ? byId.get(current.parentId) : null;
  }

  return pathRows.filter((item) => !genericNames.has(item.name));
}

function stripSuffix(value) {
  let output = value;
  let previous = "";
  while (output !== previous) {
    previous = output;
    output = output.replace(suffixPattern, "");
  }
  return output;
}

const index = rows.map((row) => {
  const pathRows = getPath(row);
  const names = pathRows.map((item) => item.name);
  const fullName = names.join("");
  const shortName = stripSuffix(row.name);
  if (!fullName || !shortName) return null;

  // Compact encoding: [name, shortName, fullName, lon, lat, level]
  return [row.name, shortName, fullName, Number(row.lon.toFixed(6)), Number(row.lat.toFixed(6)), names.length];
}).filter(Boolean);

const code = `// Auto-generated by tools/build-china-city-index.js from assets/china-regions.sql
// Provides a client-side fallback index for Chinese cities/districts/counties.
// Format per entry: [name, shortName, fullName, lon, lat, level]
const chinaCityIndex = ${JSON.stringify(index)};
if (typeof window !== "undefined") window.chinaCityIndex = chinaCityIndex;
`;

fs.writeFileSync(outputPath, code, "utf8");
console.log(`Wrote ${index.length} cities to ${path.relative(root, outputPath)} (${(fs.statSync(outputPath).size / 1024).toFixed(1)} KB)`);
